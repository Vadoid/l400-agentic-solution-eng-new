def load_gitignore_names(workspace_root: str) -> set:
    """Dynamically loads simple ignored directory/file names from .gitignore/.dockerignore/.gcloudignore."""
    dynamic_ignores = set()
    for ignore_file in (".gitignore", ".dockerignore", ".gcloudignore"):
        p = os.path.join(workspace_root, ignore_file)
        if not os.path.isfile(p):
            continue
        try:
            with open(p, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    s = line.strip()
                    if not s or s.startswith("#") or s.startswith("!"):
                        continue
                    s = s.strip("/")
                    if "/" not in s and "*" not in s and "?" not in s:
                        dynamic_ignores.add(s)
        except OSError:
            pass
    return dynamic_ignores


def is_ignored_filename(fname: str) -> bool:
    """Checks if a filename is a lockfile, OS artifact, or ignored config."""
    if not fname or fname.startswith(".") or fname in IGNORED_FILENAMES:
        return True
    lower = fname.lower()
    if lower.endswith((".lock", "-lock.json", "-lock.yaml", ".lock.json")):
        return True
    return False


def split_frontmatter(raw_text: str) -> Tuple[Optional[Dict[str, Any]], str]:
    """Splits YAML frontmatter (if present) from the Markdown body."""
    match = FRONTMATTER_RE.match(raw_text)
    if not match:
        return None, raw_text
    fm_text = match.group(1)
    body = raw_text[match.end():]
    if yaml is not None:
        try:
            parsed = yaml.safe_load(fm_text)
            if isinstance(parsed, dict):
                return parsed, body
        except Exception:
            pass
    return None, body


def split_spec_and_deltas(body_clean: str) -> Tuple[str, str]:
    """
    Splits the Markdown body into:
      (original_spec_body, deltas_section_text)
    where `original_spec_body` is the immutable human specification above
    `## Implementation Notes & Design Deltas` and `deltas_section_text` is the
    implementation delta section at the bottom (empty string if not present).
    """
    match = DELTAS_HEADING_RE.search(body_clean)
    if not match:
        return body_clean.rstrip() + "\n", ""
    orig = body_clean[:match.start()].rstrip() + "\n"
    deltas = match.group(1).strip()
    return orig, deltas


def extract_design_deltas(deltas_section: str) -> Tuple[List[str], bool]:
    """
    Extracts structured bullet items from `## Implementation Notes & Design Deltas`.
    Returns (deltas_list, is_pending_placeholder).
    """
    if not deltas_section.strip():
        return [], True

    lines = deltas_section.splitlines()
    items: List[str] = []
    current_top_category = ""

    for line in lines:
        if line.strip().startswith("##"):
            continue
        stripped = line.strip()
        if not stripped:
            continue
        indent = len(line) - len(line.lstrip(" "))
        bullet_m = re.match(r"^[-*]\s+(.+)$", stripped)
        if not bullet_m:
            continue
        content = bullet_m.group(1).strip()

        if indent < 2:
            cat_only_m = re.match(r"^\*\*([^*]+?):?\*\*:?\s*$", content)
            if cat_only_m:
                current_top_category = cat_only_m.group(1).strip().rstrip(":")
            else:
                current_top_category = ""
                items.append(content)
        else:
            if current_top_category:
                items.append(f"**{current_top_category}** — {content}")
            else:
                items.append(content)

    is_placeholder = (
        not items
        or any("_Pending agent documentation" in item for item in items)
    )
    return items, is_placeholder


def compute_sha256_short(text: str) -> str:
    """Computes a 12-character SHA-256 hex digest of normalized text content."""
    normalized = text.strip().replace("\r\n", "\n")
    if not normalized:
        return "none"
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:12]


def is_binary_file(filepath: str) -> bool:
    """Checks if an existing file on disk appears to be binary (contains null bytes in first 1KB)."""
    try:
        with open(filepath, "rb") as f:
            chunk = f.read(1024)
        return b"\x00" in chunk
    except OSError:
        return False


def is_source_file(filepath: str) -> bool:
    """
    Language-agnostic check using a blocklist rather than an allowlist:
    Accepts any non-binary, non-ignored source/project file across any stack
    (Python, .NET/C#/F#, Go, Java, Rust, C/C++, JS/TS, Terraform, SQL, etc.).
    For Markdown files inside directories, only SKILL.md is treated as source code.
    """
    base = os.path.basename(filepath)
    if is_ignored_filename(base):
        return False
    if base in EXTENSIONLESS_SOURCE_FILENAMES or base.startswith("Dockerfile."):
        return True
    _, ext = os.path.splitext(base)
    if not ext:
        return False
    ext_lower = ext.lower()
    if ext_lower == ".md":
        return base == "SKILL.md"
    if ext_lower in IGNORED_EXTENSIONS or not re.match(r"^\.[a-zA-Z][a-zA-Z0-9_-]{0,14}$", ext_lower):
        return False
    if os.path.isfile(filepath) and is_binary_file(filepath):
        return False
    return True


def list_directory_source_files(abs_dir: str, workspace_root: str) -> List[str]:
    """Lists all relevant non-ignored source files inside a directory, relative to workspace_root."""
    found: List[str] = []
    ignored_dirs = IGNORED_DIRS | load_gitignore_names(workspace_root)
    for root, dirs, files in os.walk(abs_dir):
        dirs[:] = sorted(d for d in dirs if d not in ignored_dirs and not d.startswith("."))
        for fname in sorted(files):
            if is_ignored_filename(fname):
                continue
            full_path = os.path.join(root, fname)
            if is_source_file(full_path):
                rel = os.path.relpath(full_path, workspace_root).replace("\\", "/")
                found.append(rel)
    return found


def build_workspace_file_index(workspace_root: str) -> List[str]:
    """Scans the workspace once and returns a list of relative source file paths."""
    all_files: List[str] = []
    ignored_dirs = IGNORED_DIRS | load_gitignore_names(workspace_root)
    for root, dirs, files in os.walk(workspace_root):
        dirs[:] = sorted(
            d
            for d in dirs
            if d not in ignored_dirs
            and (not d.startswith(".") or d in (".agents", ".agents/rules"))
        )
        for fname in sorted(files):
            full_path = os.path.join(root, fname)
            rel = os.path.relpath(full_path, workspace_root).replace("\\", "/")
            if rel.startswith("docs/design/"):
                continue
            if is_source_file(full_path):
                all_files.append(rel)
    return all_files


def count_existing_targets(workspace_root: str, target_files: List[str]) -> Tuple[int, int]:
    """
    Counts how many target files or directories exist in the workspace.
    Returns (existing_count, total_count).
    """
    existing_count = 0
    total_count = len(target_files)

    for rel_path in sorted(target_files):
        abs_path = os.path.join(workspace_root, rel_path)
        if os.path.isfile(abs_path):
            existing_count += 1
        elif os.path.isdir(abs_path):
            subfiles = list_directory_source_files(abs_path, workspace_root)
            if subfiles:
                existing_count += 1

    return existing_count, total_count


def extract_spec_id(filename: str, body: str) -> str:
    """Extracts the canonical spec ID (e.g., DESIGN-01, SPEC-02A, ADR-003) from filename or H1."""
    base = os.path.basename(filename)
    m = re.match(r"^([A-Z]+-[0-9]+[A-Z]?)", base)
    if m:
        return m.group(1)
    h1 = re.search(r"^#\s+([A-Z]+-[0-9]+[A-Z]?)\b", body, re.MULTILINE)
    if h1:
        return h1.group(1)
    return os.path.splitext(base)[0]


def parse_spec_family(spec_id: str) -> Tuple[str, int, str]:
    """
    Parses a spec_id like 'DESIGN-05B' into ('DESIGN', 5, 'B') for generic
    phase/sub-phase ordering and inheritance.
    """
    m = re.match(r"^([A-Z]+)-0*([0-9]+)([A-Z]?)$", spec_id)
    if not m:
        return (spec_id, 0, "")
    return (m.group(1), int(m.group(2)), m.group(3))


def extract_title(body: str, fallback: str) -> str:
    """Extracts the human-readable title from the first H1 heading."""
    m = re.search(r"^#\s+(?:[A-Z]+-[0-9]+[A-Z]?:\s*)?(.+)$", body, re.MULTILINE)
    if m:
        return m.group(1).strip()
    return fallback


def extract_summary(body: str) -> str:
    """Extracts a concise summary from `## Objective`, `## Summary`, `## Overview`, or first paragraph."""
    sec_match = re.search(
        r"^##\s+(?:Objective|Summary|Overview|Goal|Purpose)\s*\n+(.+?)(?=\n##\s+|\Z)",
        body,
        re.MULTILINE | re.DOTALL | re.IGNORECASE,
    )
    if sec_match:
        paragraph = sec_match.group(1).strip()
        return re.sub(r"\s+", " ", paragraph)

    for line in body.splitlines():
        s = line.strip()
        if s and not s.startswith("#") and not s.startswith("---"):
            return s
    return "Design specification document."


def extract_api_endpoints(body: str) -> List[str]:
    """Deterministically extracts HTTP API routes (e.g. `GET /api/status`) from markdown."""
    pattern = re.compile(r"\b(GET|POST|PUT|DELETE|PATCH)\s+(/[a-zA-Z0-9_./-]*)")
    endpoints: List[str] = []
    for method, route in pattern.findall(body):
        ep = f"{method} {route.rstrip('.,`:)')}"
        if ep not in endpoints:
            endpoints.append(ep)
    return endpoints


def strip_dot_slash(path_str: str) -> str:
    """Removes a leading './' without stripping the leading dot of hidden folders like '.agents/'."""
    s = path_str.strip()
    while s.startswith("./"):
        s = s[2:]
    return s.rstrip("/")


def looks_like_workspace_path(
    token: str,
    workspace_root: str,
    workspace_files: List[str],
) -> bool:
    """
    Filesystem-driven check for whether a backticked string represents a workspace
    file or target directory path, without hardcoding directory names.
    Single-segment top-level folder names (e.g. `src/`, `terraform/`, `.agents/rules`)
    are excluded unless they include a subpath or are a source file.
    """
    if not token or " " in token or "://" in token:
        return False
    if token.startswith((
        "/",
        "roles/",
        "projects/",
        "locations/",
        "application/",
        "text/",
        "image/",
        "audio/",
        "video/",
        "multipart/",
    )) and not token.startswith("./"):
        return False
    cleaned = strip_dot_slash(token)
    if not cleaned or re.match(r"^[0-9]+/[0-9]+$", cleaned):
        return False

    # Multi-segment paths (e.g. `src/generate-mock-data`, `evals/security-audits/`, `Controllers/HomeController.cs`)
    if "/" in cleaned:
        if os.path.exists(os.path.join(workspace_root, cleaned)):
            return True
        first_seg = cleaned.split("/", 1)[0]
        if os.path.isdir(os.path.join(workspace_root, first_seg)):
            return True
        if any(wf == cleaned or wf.startswith(cleaned + "/") or wf.endswith("/" + cleaned) for wf in workspace_files):
            return True
        if re.match(r"^\.?[a-zA-Z0-9_-]+(?:/[a-zA-Z0-9_.-]+)+$", cleaned):
            return True
        return False

    # Single-segment token: must be a file (not a bare top-level directory name like `src/` or `.agents/rules`)
    return is_source_file(cleaned)


def discover_target_files_from_body(
    body: str,
    api_endpoints: List[str],
    workspace_root: str,
    workspace_files: List[str],
) -> List[str]:
    """
    Generically discovers target implementation files for a specification by:
    1. Parsing backticked file/directory paths in the Markdown body.
    2. Expanding referenced directories into their constituent source files (if present on disk)
       or keeping the directory/file path as a pending target if not yet created.
    3. Resolving relative sub-paths against any parent directory referenced in the same spec
       before falling back to workspace root.
    4. Matching extracted HTTP API routes (e.g. `/api/triage`) against application source files.
    """
    candidates: List[str] = []
    referenced_dirs: List[str] = []
    code_spans = re.findall(r"`([^`\n]+)`", body)

    def add_candidate(rel_path: str):
        norm = strip_dot_slash(rel_path).replace("\\", "/")
        if norm and norm not in candidates and not norm.startswith("docs/design"):
            candidates.append(norm)

    for span in code_spans:
        if not looks_like_workspace_path(span, workspace_root, workspace_files):
            continue
        cleaned = strip_dot_slash(span)
        abs_candidate = os.path.join(workspace_root, cleaned)

        if os.path.isdir(abs_candidate):
            referenced_dirs.append(cleaned)
            dir_files = list_directory_source_files(abs_candidate, workspace_root)
            if dir_files:
                for df in dir_files:
                    add_candidate(df)
            else:
                add_candidate(cleaned)
        elif os.path.isfile(abs_candidate):
            parent_d = os.path.dirname(cleaned)
            if parent_d and parent_d not in referenced_dirs:
                referenced_dirs.append(parent_d)
            add_candidate(cleaned)
        else:
            matched_in_parent = False
            for rdir in referenced_dirs:
                joined = f"{rdir}/{cleaned}"
                if os.path.exists(os.path.join(workspace_root, joined)) or any(
                    c == joined or c.endswith("/" + cleaned) for c in candidates
                ):
                    add_candidate(joined)
                    matched_in_parent = True
                    break
            if matched_in_parent:
                continue

            if "/" not in cleaned:
                matches = [wf for wf in workspace_files if os.path.basename(wf) == cleaned]
                if len(matches) == 1:
                    add_candidate(matches[0])
                elif len(matches) > 1 and referenced_dirs:
                    for m in matches:
                        if any(m.startswith(d + "/") or os.path.dirname(m) == d for d in referenced_dirs):
                            add_candidate(m)
            else:
                suffix_matches = [wf for wf in workspace_files if wf.endswith("/" + cleaned)]
                if len(suffix_matches) == 1:
                    add_candidate(suffix_matches[0])
                else:
                    add_candidate(cleaned)

    # Check if the spec explicitly provisions infrastructure via Terraform (and isn't just auditing it)
    if (
        not candidates
        and re.search(r"\b(?:provision|deploy|create)\b.*\bterraform\b", body, re.IGNORECASE | re.DOTALL)
    ):
        all_tf = [wf for wf in workspace_files if wf.endswith(".tf")]
        root_tf = [wf for wf in all_tf if "modules/" not in wf and "-modules/" not in wf]
        chosen_tf = root_tf or all_tf
        if chosen_tf:
            for tf in chosen_tf:
                add_candidate(tf)
        else:
            add_candidate("terraform/main.tf")

    # If the spec defines HTTP API endpoints and didn't already identify target files,
    # search application source files (across any language) for route implementations
    if api_endpoints and not candidates:
        routes = [ep.split(" ", 1)[1] for ep in api_endpoints if " " in ep]
        for wf in workspace_files:
            if wf.startswith((".agents/", ".agents/rules/", "evals/", "tests/", "test/", "docs/")):
                continue
            if wf.endswith((".md", ".txt", ".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".csv")):
                continue
            abs_wf = os.path.join(workspace_root, wf)
            try:
                with open(abs_wf, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read()
                for route in routes:
                    if f'"{route}"' in content or f"'{route}'" in content:
                        add_candidate(wf)
                        if re.search(r"\b(Frontend|UI|HTML|Chart|Button|Modal|View|Page|Component)\b", body, re.IGNORECASE):
                            app_dir = os.path.dirname(wf)
                            for tpl in workspace_files:
                                if not tpl.startswith(app_dir + "/") or tpl == wf:
                                    continue
                                rel_sub = tpl[len(app_dir) + 1:]
                                if (
                                    "/" in rel_sub
                                    or tpl.endswith((".html", ".cshtml", ".razor", ".jsx", ".tsx", ".vue", ".svelte"))
                                ):
                                    add_candidate(tpl)
                        break
            except OSError:
                pass

    return candidates


def discover_known_datasets(design_bodies: List[str]) -> List[str]:
    """Extracts dataset identifiers declared across any design specification."""
    datasets: List[str] = []
    for body in design_bodies:
        for m in re.findall(r"Dataset:\s*`([a-zA-Z][a-zA-Z0-9_]*)`", body, re.IGNORECASE):
            if m not in datasets:
                datasets.append(m)
    return datasets


def extract_gcp_resources_generic(
    body: str,
    known_datasets: List[str],
) -> List[str]:
    """
    Generically extracts Google Cloud resource references directly from the
    specification Markdown grammar without relying on environment config files
    or hardcoded project/table/language lists.
    """
    resources: List[str] = []

    def add_res(res_str: str):
        if res_str and res_str not in resources:
            resources.append(res_str)

    default_dataset = known_datasets[0] if known_datasets else None
    ds_match = re.search(r"Dataset:\s*`([a-zA-Z][a-zA-Z0-9_]*)`", body, re.IGNORECASE)
    if ds_match:
        default_dataset = ds_match.group(1)

    # 1. Qualified `<dataset>.<object>` references where `<dataset>` is a known dataset
    for ds, obj in re.findall(r"`([a-zA-Z][a-zA-Z0-9_]*)\.([a-zA-Z][a-zA-Z0-9_]*)`", body):
        if ds in known_datasets or ds == default_dataset:
            add_res(f"bigquery:{ds}.{obj}")

    # 2. Unqualified BigQuery table/view/model identifiers in SQL/BigQuery contexts
    if re.search(r"\b(BigQuery|BQ|SQL|table|tables|view|model|telemetry|seed|schema)\b", body, re.IGNORECASE):
        prep_pattern = re.compile(
            r"\b(?:table|tables|view|model|into|from|query|queries|populate|seed|updates?|write\s+to)\s+(?:named\s+)?`([a-zA-Z][a-zA-Z0-9_]+)`",
            re.IGNORECASE,
        )
        bullet_pattern = re.compile(r"^\s*-\s*`([a-zA-Z][a-zA-Z0-9_]+)`\s*(?:\(|:)", re.MULTILINE)

        candidates_bq: List[str] = []
        for m in prep_pattern.findall(body):
            candidates_bq.append(m.strip())
        for m in bullet_pattern.findall(body):
            candidates_bq.append(m.strip())
        for line in body.splitlines():
            if re.search(r"\b(?:Query|Queries|correlates)\b", line, re.IGNORECASE):
                for tok in re.findall(r"`([a-zA-Z][a-zA-Z0-9_]+)`", line):
                    candidates_bq.append(tok.strip())

        for token in candidates_bq:
            # Snake_case identifiers that contain at least one lowercase letter (automatically excluding
            # ALL_CAPS SQL types/options like INT64, FLOAT64, ARIMA_PLUS, AUTO_ARIMA, TRUE, FALSE)
            if (
                "_" in token
                and not token.isupper()
                and token != default_dataset
                and token not in known_datasets
                and not is_source_file(token)
            ):
                prefix = f"{default_dataset}." if default_dataset else ""
                add_res(f"bigquery:{prefix}{token}")

    # 3. Pub/Sub, Artifact Registry, Cloud Run, Vertex AI, Secret Manager, IAP
    for topic_m in re.findall(r"\btopic\s*\(?`([a-zA-Z0-9_-]+)`\)?", body, re.IGNORECASE):
        add_res(f"pubsub:topic/{topic_m}")
    for sub_m in re.findall(r"\bsubscription\s*\(?`([a-zA-Z0-9_-]+)`\)?", body, re.IGNORECASE):
        add_res(f"pubsub:subscription/{sub_m}")
    for ar_m in re.findall(r"\brepository\s*\(?`([a-zA-Z0-9_-]+)`\)?", body, re.IGNORECASE):
        add_res(f"artifact-registry:{ar_m}")
    for cr_m in re.findall(r"Cloud Run(?:\s+service)?\s+`([a-zA-Z0-9_-]+)`", body, re.IGNORECASE):
        add_res(f"cloud-run:{cr_m}")
    if "Cloud Run" in body and not any(r.startswith("cloud-run:") for r in resources):
        add_res("cloud-run:service")

    for model_m in re.findall(r"\b(gemini-[0-9.]+-[a-z0-9-]+|text-embedding-[a-z0-9-]+)\b", body, re.IGNORECASE):
        add_res(f"vertex-ai:{model_m}")

    if re.search(r"\bSecret Manager\b", body, re.IGNORECASE):
        add_res("secret-manager")
    if re.search(r"\b(IAP|Identity-Aware Proxy)\b", body):
        add_res("iap:cloud-run-protection")

    return resources


def is_manifest_or_container_file(rel_path: str) -> bool:
    """Checks if a file is a build/container/dependency manifest rather than application logic."""
    base = os.path.basename(rel_path)
    if base in EXTENSIONLESS_SOURCE_FILENAMES or base.startswith("Dockerfile"):
        return True
    _, ext = os.path.splitext(base.lower())
    return ext in (".txt", ".json", ".toml", ".yaml", ".yml", ".csproj", ".fsproj", ".vbproj", ".mod")


def infer_cross_spec_relationships(specs_meta: List[Dict[str, Any]]) -> None:
    """
    Generically infers `target_files` inheritance (for multi-part specs like 05A -> 05B -> 05C)
    and `depends_on` relationships across all discovered specs.
    """
    spec_ids = [s["spec_id"] for s in specs_meta]

    families: Dict[Tuple[str, int], List[Dict[str, Any]]] = {}
    for s in specs_meta:
        prefix, num, suffix = parse_spec_family(s["spec_id"])
        families.setdefault((prefix, num), []).append(s)

    for fam_key, fam_specs in families.items():
        if len(fam_specs) > 1:
            for idx in range(1, len(fam_specs)):
                prev_spec = fam_specs[idx - 1]
                curr_spec = fam_specs[idx]
                if prev_spec["spec_id"] not in curr_spec["depends_on"]:
                    curr_spec["depends_on"].append(prev_spec["spec_id"])
                if not curr_spec["target_files"] and fam_specs[0]["target_files"]:
                    curr_spec["target_files"] = [
                        tf for tf in fam_specs[0]["target_files"]
                        if not is_manifest_or_container_file(tf)
                    ] or list(fam_specs[0]["target_files"])

    resource_producer: Dict[str, str] = {}
    for s in specs_meta:
        for r in s["gcp_resources"]:
            if r not in resource_producer:
                resource_producer[r] = s["spec_id"]

    for i, s in enumerate(specs_meta):
        deps: List[str] = list(s["depends_on"])

        for other_id in spec_ids:
            if other_id != s["spec_id"] and re.search(rf"\b{re.escape(other_id)}\b", s["_orig_body"]):
                if other_id not in deps:
                    deps.append(other_id)

        for r in s["gcp_resources"]:
            producer_id = resource_producer.get(r)
            if producer_id and producer_id != s["spec_id"]:
                prod_idx = next((idx for idx, item in enumerate(specs_meta) if item["spec_id"] == producer_id), -1)
                if 0 <= prod_idx < i and producer_id not in deps:
                    deps.append(producer_id)

        s["depends_on"] = sorted(
            deps,
            key=lambda d: spec_ids.index(d) if d in spec_ids else 999,
        )


def format_frontmatter_yaml(metadata: Dict[str, Any]) -> str:
    """Serializes frontmatter dictionary to clean, deterministic YAML."""
    ordered_keys = [
        "spec_id",
        "status",
        "spec_sha256",
        "depends_on",
        "target_files",
    ]
    ordered_dict = {k: metadata[k] for k in ordered_keys if k in metadata}
    if yaml is not None:
        dumped = yaml.safe_dump(
            ordered_dict,
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=True,
            width=100,
        ).strip()
        return f"---\n{dumped}\n---\n\n"

    lines = ["---"]
    for k, v in ordered_dict.items():
        if isinstance(v, list):
            if not v:
                lines.append(f"{k}: []")
            else:
                lines.append(f"{k}:")
                for item in v:
                    lines.append(f"  - {json.dumps(item)}")
        else:
            lines.append(f"{k}: {json.dumps(v)}")
    lines.append("---\n\n")
    return "\n".join(lines)


def generate_index_markdown(
    specs_meta: List[Dict[str, Any]],
) -> str:
    """Generates the compact `docs/design/index.md` Progressive Disclosure Spec Ledger."""
    total_specs = len(specs_meta)
    implemented_specs = sum(
        1 for s in specs_meta if s["status"] == "implemented"
    )

    frontmatter = {
        "ledger_version": "1.0",
        "total_specs": total_specs,
        "implemented_specs": implemented_specs,
    }
    if yaml is not None:
        fm_str = yaml.safe_dump(frontmatter, sort_keys=False).strip()
    else:
        fm_str = "\n".join(f"{k}: {json.dumps(v)}" for k, v in frontmatter.items())

    lines = [
        "---",
        fm_str,
        "---",
        "",
        "# Architectural Design Ledger (Progressive Disclosure Index)",
        "",
        "> **Agent Instructions:** Read this index first to locate which design specification file governs a feature or implementation target. Only load the full Markdown body (including `## Implementation Notes & Design Deltas (Auto-Generated by Agent Harness)`) of the specific specification file(s) relevant to your current task.",
        "",
        "## Specification Routing Table",
        "",
        "| Spec ID | Title | Status | Depends On | Target Files | Spec SHA |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    if not specs_meta:
        lines.append(
            "| — | *No design specifications found yet* | `empty` | — | — | — |"
        )
    else:
        for s in specs_meta:
            spec_link = f"[{s['spec_id']}](./{s['filename']})"
            deps = ", ".join(s["depends_on"]) if s["depends_on"] else "None"
            targets = ", ".join(f"`{t}`" for t in s["target_files"]) if s["target_files"] else "None"
            lines.append(
                f"| {spec_link} | {s['title']} | `{s['status']}` | {deps} | {targets} | `{s['spec_sha256']}` |"
            )

    lines.extend([
        "",
        "## Specification Summaries",
        "",
    ])

    if not specs_meta:
        lines.append("_No design specifications have been authored in `docs/design/` yet._")
        lines.append("")
    else:
        for s in specs_meta:
            lines.append(
                f"- **[{s['spec_id']}: {s['title']}](./{s['filename']}) (`{s['status']}`):** {s['summary']}"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def index_design_specs(
    design_dir: str = "docs/design",
    workspace_root: str = ".",
    force: bool = False,
    check_only: bool = False,
) -> Dict[str, Any]:
    """
    Scans all markdown specifications in `design_dir` (excluding `index.md`),
    updates their YAML frontmatter, auto-scaffolds `## Implementation Notes & Design Deltas`
    if missing on implemented specs, and writes `docs/design/index.md`.
    """
    workspace_root = os.path.abspath(workspace_root)
    abs_design_dir = (
        design_dir
        if os.path.isabs(design_dir)
        else os.path.abspath(os.path.join(workspace_root, design_dir))
    )

    config_path = os.path.join(workspace_root, "agent-config.json")
    config: Dict[str, Any] = {}
    if os.path.isfile(config_path):
        try:
            with open(config_path, "r", encoding="utf-8") as cf:
                config = json.load(cf)
        except Exception:
            config = {}

    project_id = (
        config.get("gcp-project-id")
        or config.get("project_id")
        or config.get("projectId")
        or os.path.basename(workspace_root)
    )

    workspace_files = build_workspace_file_index(workspace_root)

    all_md = sorted(glob.glob(os.path.join(abs_design_dir, "*.md")))
    design_files = [
        p for p in all_md
        if os.path.basename(p).lower() not in ("index.md", "readme.md")
    ]

    specs_meta: List[Dict[str, Any]] = []
    updated_files: List[str] = []
    drift_events: List[Dict[str, str]] = []
    missing_design_deltas: List[str] = []

    # Pre-scan spec bodies to discover any dataset names declared across the specs
    parsed_files: List[Tuple[str, str, Optional[Dict[str, Any]], str, str, str]] = []
    orig_bodies: List[str] = []
    for filepath in design_files:
        filename = os.path.basename(filepath)
        with open(filepath, "r", encoding="utf-8") as f:
            raw_text = f.read()
        existing_fm, body = split_frontmatter(raw_text)
        body_clean = body.lstrip("\r\n")
        orig_body, deltas_section = split_spec_and_deltas(body_clean)
        parsed_files.append((filepath, filename, existing_fm, body_clean, orig_body, deltas_section))
        orig_bodies.append(orig_body)

    known_datasets = discover_known_datasets(orig_bodies)

    # Pass 1: Extract per-file metadata from the human's original Markdown body
    for filepath, filename, existing_fm, body_clean, orig_body, deltas_section in parsed_files:
        spec_id = extract_spec_id(filename, orig_body)
        title = extract_title(orig_body, spec_id)
        summary = extract_summary(orig_body)
        api_endpoints = extract_api_endpoints(orig_body)
        target_files = discover_target_files_from_body(
            orig_body, api_endpoints, workspace_root, workspace_files
        )
        gcp_resources = extract_gcp_resources_generic(orig_body, known_datasets)

        specs_meta.append({
            "spec_id": spec_id,
            "title": title,
            "summary": summary,
            "depends_on": [],
            "target_files": target_files,
            "api_endpoints": api_endpoints,
            "gcp_resources": gcp_resources,
            "design_deltas": [],
            "filename": filename,
            "_filepath": filepath,
            "_existing_fm": existing_fm,
            "_body_clean": body_clean,
            "_orig_body": orig_body,
            "_deltas_section": deltas_section,
        })

    # Pass 2: Infer cross-spec dependencies and multi-part spec family inheritance
    infer_cross_spec_relationships(specs_meta)

    # Pass 3: Compute spec_sha256, auto-scaffold missing deltas on implemented specs, detect prompt drift, and write frontmatter
    legacy_frontmatter_keys = (
        "title",
        "last_indexed_at",
        "deltas_sha256",
        "code_sha256",
        "api_endpoints",
        "gcp_resources",
        "summary",
        "design_deltas",
    )

    for s in specs_meta:
        filepath = s.pop("_filepath")
        existing_fm = s.pop("_existing_fm")
        body_clean = s.pop("_body_clean")
        orig_body = s.pop("_orig_body")
        deltas_section = s.pop("_deltas_section")
        spec_id = s["spec_id"]

        existing_targets, total_targets = count_existing_targets(
            workspace_root, s["target_files"]
        )

        if total_targets > 0 and existing_targets == total_targets:
            base_status = "implemented"
        elif existing_targets > 0:
            base_status = "in_progress"
        else:
            base_status = "pending"

        # Auto-scaffold `## Implementation Notes & Design Deltas (Auto-Generated by Agent Harness)` if code exists and section is missing
        scaffolded_now = False
        if base_status in ("implemented", "in_progress") and not deltas_section.strip():
            if not check_only:
                body_clean = orig_body.rstrip() + DEFAULT_DELTAS_SCAFFOLD
                _, deltas_section = split_spec_and_deltas(body_clean)
                scaffolded_now = True
        elif deltas_section.strip() and not deltas_section.splitlines()[0].strip().endswith("(Auto-Generated by Agent Harness)"):
            if not check_only:
                lines_d = deltas_section.splitlines()
                lines_d[0] = CANONICAL_DELTAS_HEADING
                deltas_section = "\n".join(lines_d)
                body_clean = orig_body.rstrip() + "\n\n---\n\n" + deltas_section + "\n"
                scaffolded_now = True

        design_deltas, is_placeholder_deltas = extract_design_deltas(deltas_section)
        if base_status in ("implemented", "in_progress") and is_placeholder_deltas:
            missing_design_deltas.append(spec_id)

        s["design_deltas"] = design_deltas

        spec_sha = compute_sha256_short(orig_body)

        drift_type = None
        if existing_fm:
            prev_spec_sha = existing_fm.get("spec_sha256")
            if prev_spec_sha and prev_spec_sha != spec_sha:
                drift_type = "spec_modified_needs_sync"
                drift_events.append({
                    "spec_id": spec_id,
                    "drift": drift_type,
                    "prev_spec_sha256": str(prev_spec_sha),
                    "new_spec_sha256": spec_sha,
                })

        effective_status = drift_type if (check_only and drift_type) else base_status

        has_legacy_keys = (
            existing_fm is not None
            and any(k in existing_fm for k in legacy_frontmatter_keys)
        )

        unchanged = (
            existing_fm is not None
            and not force
            and not scaffolded_now
            and not has_legacy_keys
            and existing_fm.get("spec_id") == spec_id
            and existing_fm.get("spec_sha256") == spec_sha
            and existing_fm.get("status") == effective_status
            and existing_fm.get("depends_on") == s["depends_on"]
            and existing_fm.get("target_files") == s["target_files"]
        )

        s["status"] = effective_status
        s["spec_sha256"] = spec_sha

        if not check_only and not unchanged:
            new_content = format_frontmatter_yaml(s) + body_clean
            with open(filepath, "w", encoding="utf-8") as wf:
                wf.write(new_content)
            updated_files.append(os.path.relpath(filepath, workspace_root))

    index_path = os.path.join(abs_design_dir, "index.md")
    if not check_only:
        os.makedirs(abs_design_dir, exist_ok=True)
        index_md = generate_index_markdown(specs_meta)
        with open(index_path, "w", encoding="utf-8") as idx_f:
            idx_f.write(index_md)

    return {
        "status": "CHECK_COMPLETED" if check_only else "SUCCESS",
        "project_id": project_id,
        "total_specs": len(specs_meta),
        "implemented_specs": sum(1 for s in specs_meta if s["status"] == "implemented"),
        "updated_spec_files": updated_files,
        "missing_design_deltas": missing_design_deltas,
        "drift_events": drift_events,
        "index_file": os.path.relpath(index_path, workspace_root),
    }


def main():
    parser = argparse.ArgumentParser(
        description="Generically index docs/design/*.md specifications with YAML frontmatter and generate docs/design/index.md."
    )
    parser.add_argument(
        "--design-dir",
        default="docs/design",
        help="Path to the design documents directory (default: docs/design)",
    )
    parser.add_argument(
        "--workspace-root",
        default=".",
        help="Path to the repository workspace root (default: current directory)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Force rewrite of YAML frontmatter across all specs",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check for spec/code drift without modifying any files",
    )
    args = parser.parse_args()

    result = index_design_specs(
        design_dir=args.design_dir,
        workspace_root=args.workspace_root,
        force=args.force,
        check_only=args.check,
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
