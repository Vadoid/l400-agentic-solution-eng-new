#!/usr/bin/env python3
"""
Agent Skill: spec-ledger
Generic, project-agnostic design specification indexer.

Deterministically indexes design specifications in `docs/design/*.md` by:
1. Separating the human's original specification body from the bottom
   `## Implementation Notes & Design Deltas (Auto-Generated by Agent Harness)`
   section so the original prompt remains an immutable audit trail (`spec_sha256`).
2. Auto-scaffolding `## Implementation Notes & Design Deltas (Auto-Generated by Agent Harness)`
   at the bottom of any implemented/in-progress specification if missing, and
   flagging specs with pending/undocumented deltas (`missing_design_deltas`).
3. Extracting lean, zero-duplication YAML frontmatter (`spec_id`, `status`,
   `spec_sha256`, `depends_on`, `target_files`) directly from Markdown grammar
   and workspace scanning.
4. Generating a compact Progressive Disclosure routing index at
   `docs/design/index.md` (`ledger_version: "1.0"`) with a routing table and
   one-line summaries.
"""

